use Symfony\Bundle\FrameworkBundle\Test\KernelTestCase;

/**
 * [Description ActuatorRepositoryTest]
 */
class ActuatorRepositoryTest extends KernelTestCase
{
    private static $erreurCode200 = 'Erreur le code retour doit être 200';
    private static $mavenKey = 'fr.ma-moulinette:app1';
    private static $nomApplication = 'Application 01';
    private static $url = 'http://ma-moulinette.fr/app01';
    private static $actuatorUser = 'user1';
    private static $actuatorPassword = 'password1';
    private static $personne ='John Doe';

    protected function setUp(): void
    {
        self::bootKernel();
        $container = static::getContainer();
        $entityManager = $container->get('doctrine')->getManager();

        // Réinitialiser la séquence
        $connection = $entityManager->getConnection();
        $platform = $connection->getDatabasePlatform('SET search_path TO ma_moulinette_test');

        if ($platform instanceof \Doctrine\DBAL\Platforms\PostgreSqlPlatform) {
            $sequence = 'ma_moulinette.actuator_id_seq';
            $connection->executeQuery("SELECT setval('$sequence', 1, false);");
        }

        $purger = new ORMPurger($entityManager);
        $executor = new ORMExecutor($entityManager, $purger);
        $executor->execute([new ActuatorFixtures()]);
    }


    protected function tearDown(): void
    {
        parent::tearDown();

        // On se déconnecte pour éviter des problèmes de mémoires
        $container = static::getContainer();
        $entityManager = $container->get('doctrine')->getManager();
        $entityManager->close();
        $entityManager = null;
    }
}

-- Laurent HADJADJ, 20/11/2026 - Création des tables du pipeline npm audit :
-- npm_processing_queue (file d'ingestion), npm_scan (1 par rapport ingéré),
-- npm_dependency (référentiel dédupliqué par name), npm_vulnerability
-- (référentiel dédupliqué par advisory_id) et npm_finding (jointure
-- scan x dependency x vulnerability).
-- Gabarit : migrations/POSTGRESQL/20_tables/npm_*.sql (fichiers d'install
-- complet) — même pattern que le pipeline ZAP (10_create_zap_tables.sql) et
-- OWASP DependencyCheck. Flux : push externe (CI) via
-- POST /api/secure/npm-audit/upload, totalement découplé des pipelines
-- Collecte.
-- npm_processing_queue.payload_gz enveloppe 1 ou 2 rapports npm audit bruts
-- ({"full": {...}, "prodOnly": {...}}) : npm audit --json ne dit pas, par
-- vulnérabilité, si le paquet concerné est en prod ou en dev - prodOnly
-- (optionnel) permet à l'ingester de croiser et déterminer
-- npm_finding.is_prod de façon fiable, en un seul upload (pas 2 requêtes
-- à synchroniser).

\c ma_moulinette postgres;

-- ===============================================
-- npm_processing_queue
-- ===============================================
DO $$
DECLARE
    table_exists BOOLEAN;
BEGIN
    SELECT EXISTS (
        SELECT FROM pg_catalog.pg_tables
        WHERE schemaname = 'ma_moulinette' AND tablename = 'npm_processing_queue'
    ) INTO table_exists;

    IF table_exists THEN
        RAISE NOTICE 'La table ma_moulinette.npm_processing_queue existe déjà.';
    ELSE
        CREATE TABLE ma_moulinette.npm_processing_queue
        (
            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            ulid              VARCHAR(26) NOT NULL UNIQUE,
            payload_gz        BYTEA NOT NULL,
            payload_sha256    CHAR(64) NOT NULL,
            payload_size      INTEGER NOT NULL,
            content_type      VARCHAR(16) NOT NULL,
            project_group     VARCHAR(255) NOT NULL,
            project_artifact  VARCHAR(255) NOT NULL,
            project_version   VARCHAR(64)  NOT NULL,
            status            VARCHAR(16) NOT NULL DEFAULT 'queued',
            attempts          INTEGER NOT NULL DEFAULT 0,
            created_at        TIMESTAMP(0) WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP(0),
            started_at        TIMESTAMP(0) WITH TIME ZONE NULL,
            processed_at      TIMESTAMP(0) WITH TIME ZONE NULL,
            error_message     TEXT NULL
        );
        RAISE NOTICE 'La table ma_moulinette.npm_processing_queue a été créée.';
    END IF;

    ALTER TABLE ma_moulinette.npm_processing_queue OWNER TO db_user;
    GRANT ALL ON TABLE ma_moulinette.npm_processing_queue TO db_user;

    COMMENT ON TABLE ma_moulinette.npm_processing_queue IS 'Queue d''ingestion des rapports npm audit postes par la CI.';
    COMMENT ON COLUMN ma_moulinette.npm_processing_queue.ulid IS 'Identifiant public renvoyé au client (ULID Crockford base32).';
    COMMENT ON COLUMN ma_moulinette.npm_processing_queue.payload_sha256 IS 'sha256 du JSON décompressé - cle d''idempotence.';
    COMMENT ON COLUMN ma_moulinette.npm_processing_queue.project_group IS 'Identification projet fournie par la CI (en-tête X-Project-Group) - absente du payload npm audit lui-même.';
    COMMENT ON COLUMN ma_moulinette.npm_processing_queue.payload_gz IS 'JSON npm audit compresse (gzip niveau 6), enveloppe 1 ou 2 rapports bruts ({"full": {...}, "prodOnly": {...}}) - prodOnly optionnel, pour determiner npm_finding.is_prod par croisement.';
    COMMENT ON COLUMN ma_moulinette.npm_processing_queue.status IS 'queued | processing | done | failed';

    CREATE INDEX IF NOT EXISTS idx_npm_queue_status_created ON ma_moulinette.npm_processing_queue(status, created_at) WHERE status IN ('queued', 'processing');
    CREATE INDEX IF NOT EXISTS idx_npm_queue_project ON ma_moulinette.npm_processing_queue(project_group, project_artifact, project_version);
    CREATE INDEX IF NOT EXISTS idx_npm_queue_created ON ma_moulinette.npm_processing_queue(created_at);

    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'uq_npm_payload_sha256') THEN
        ALTER TABLE ma_moulinette.npm_processing_queue ADD CONSTRAINT uq_npm_payload_sha256 UNIQUE (payload_sha256);
    END IF;

    RAISE NOTICE 'npm_processing_queue : droits, commentaires, indexes et contraintes à jour.';
END $$;

-- ===============================================
-- npm_scan
-- ===============================================
DO $$
DECLARE
    table_exists BOOLEAN;
BEGIN
    SELECT EXISTS (
        SELECT FROM pg_catalog.pg_tables
        WHERE schemaname = 'ma_moulinette' AND tablename = 'npm_scan'
    ) INTO table_exists;

    IF table_exists THEN
        RAISE NOTICE 'La table ma_moulinette.npm_scan existe déjà.';
    ELSE
        CREATE TABLE ma_moulinette.npm_scan
        (
            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            queue_id                BIGINT NULL,
            project_group           VARCHAR(255) NOT NULL,
            project_artifact        VARCHAR(255) NOT NULL,
            project_version         VARCHAR(64) NOT NULL,
            scan_date                TIMESTAMP(0) WITH TIME ZONE NOT NULL,
            audit_report_version    VARCHAR(8) NULL,
            vuln_count_critical     INTEGER NOT NULL DEFAULT 0,
            vuln_count_high         INTEGER NOT NULL DEFAULT 0,
            vuln_count_moderate     INTEGER NOT NULL DEFAULT 0,
            vuln_count_low          INTEGER NOT NULL DEFAULT 0,
            vuln_count_info         INTEGER NOT NULL DEFAULT 0,
            vuln_count_total        INTEGER NOT NULL DEFAULT 0,
            dep_count_prod          INTEGER NOT NULL DEFAULT 0,
            dep_count_dev           INTEGER NOT NULL DEFAULT 0,
            dep_count_optional      INTEGER NOT NULL DEFAULT 0,
            dep_count_peer          INTEGER NOT NULL DEFAULT 0,
            dep_count_peer_optional INTEGER NOT NULL DEFAULT 0,
            dep_count_total         INTEGER NOT NULL DEFAULT 0,
            created_at               TIMESTAMP(0) WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP(0)
        );
        RAISE NOTICE 'La table ma_moulinette.npm_scan a été créée.';
    END IF;

    ALTER TABLE ma_moulinette.npm_scan OWNER TO db_user;
    GRANT ALL ON TABLE ma_moulinette.npm_scan TO db_user;

    COMMENT ON TABLE  ma_moulinette.npm_scan IS '1 scan = 1 rapport npm audit pour (projet, version, date). Compteurs pre-calcules, repris directement de metadata du rapport.';
    COMMENT ON COLUMN ma_moulinette.npm_scan.queue_id IS 'Lien vers la row source dans npm_processing_queue (audit/retraitement).';
    COMMENT ON COLUMN ma_moulinette.npm_scan.vuln_count_moderate IS 'npm utilise "moderate", pas "medium" comme DependencyCheck - terminologie npm native conservee.';
    COMMENT ON COLUMN ma_moulinette.npm_scan.dep_count_prod IS 'metadata.dependencies.prod - sans equivalent DependencyCheck (pas de notion prod/dev pour un .jar Maven).';

    CREATE INDEX IF NOT EXISTS idx_npm_scan_project ON ma_moulinette.npm_scan(project_group, project_artifact, project_version, scan_date DESC);
    CREATE INDEX IF NOT EXISTS idx_npm_scan_recent ON ma_moulinette.npm_scan(scan_date DESC);

    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'uq_npm_scan_project_version_date') THEN
        ALTER TABLE ma_moulinette.npm_scan ADD CONSTRAINT uq_npm_scan_project_version_date UNIQUE (project_group, project_artifact, project_version, scan_date);
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'fk_npm_scan_queue') THEN
        ALTER TABLE ma_moulinette.npm_scan ADD CONSTRAINT fk_npm_scan_queue FOREIGN KEY (queue_id)
            REFERENCES ma_moulinette.npm_processing_queue(id) ON DELETE SET NULL;
    END IF;

    RAISE NOTICE 'npm_scan : droits, commentaires, indexes et contraintes à jour.';
END $$;


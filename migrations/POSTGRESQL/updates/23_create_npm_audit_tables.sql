-- ===============================================
-- npm_finding (dépend de npm_scan, npm_dependency, npm_vulnerability)
-- ===============================================
DO $$
DECLARE
    table_exists BOOLEAN;
BEGIN
    SELECT EXISTS (
        SELECT FROM pg_catalog.pg_tables
        WHERE schemaname = 'ma_moulinette' AND tablename = 'npm_finding'
    ) INTO table_exists;

    IF table_exists THEN
        RAISE NOTICE 'La table ma_moulinette.npm_finding existe déjà.';
    ELSE
        CREATE TABLE ma_moulinette.npm_finding
        (
            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            scan_id              BIGINT NOT NULL,
            dependency_id        BIGINT NOT NULL,
            vulnerability_id     BIGINT NOT NULL,
            severity_at_scan     VARCHAR(16) NOT NULL,
            cvss_at_scan         NUMERIC(3, 1) NULL,
            range                VARCHAR(255) NULL,
            installed_version    VARCHAR(255) NULL,
            is_direct            BOOLEAN NOT NULL DEFAULT false,
            fix_available        BOOLEAN NOT NULL DEFAULT false,
            fix_to_version       VARCHAR(64) NULL,
            fix_is_semver_major  BOOLEAN NULL,
            is_prod              BOOLEAN NULL,
            created_at           TIMESTAMP(0) WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP(0)
        );
        RAISE NOTICE 'La table ma_moulinette.npm_finding a été créée.';
    END IF;

    -- MODIF 2026-11-20 : ADD COLUMN IF NOT EXISTS pour les bases où
    -- npm_finding existait déjà avant l'ajout de installed_version (table
    -- créée par une exécution antérieure de ce même script).
    ALTER TABLE ma_moulinette.npm_finding ADD COLUMN IF NOT EXISTS installed_version VARCHAR(255) NULL;

    ALTER TABLE ma_moulinette.npm_finding OWNER TO db_user;
    GRANT ALL ON TABLE ma_moulinette.npm_finding TO db_user;

    COMMENT ON TABLE  ma_moulinette.npm_finding IS 'Jointure scan x dependency x vulnerability. Snapshot severity/cvss au moment du scan.';
    COMMENT ON COLUMN ma_moulinette.npm_finding.range IS 'Plage de version vulnerable constatee (vulnerabilities[name].range) - PAS une version installee exacte, npm audit --json ne la restitue pas de facon fiable.';
    COMMENT ON COLUMN ma_moulinette.npm_finding.installed_version IS 'Version(s) reellement installee(s), si la CI a aussi envoye un rapport "installed" (npm ls --all --json) dans l''enveloppe d''upload. NULL si absent. Plusieurs versions distinctes jointes par ", " en cas de conflit de resolution npm.';
    COMMENT ON COLUMN ma_moulinette.npm_finding.is_prod IS 'NULL = un seul rapport recu pour l''instant (croisement avec le rapport prod-only pas encore fait) ; true/false = determine apres croisement. Jamais une sous-estimation silencieuse du risque prod.';

    CREATE INDEX IF NOT EXISTS idx_npm_finding_scan ON ma_moulinette.npm_finding(scan_id);
    CREATE INDEX IF NOT EXISTS idx_npm_finding_vulnerability ON ma_moulinette.npm_finding(vulnerability_id);
    CREATE INDEX IF NOT EXISTS idx_npm_finding_dependency ON ma_moulinette.npm_finding(dependency_id);
    CREATE INDEX IF NOT EXISTS idx_npm_finding_severity ON ma_moulinette.npm_finding(severity_at_scan);

    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'uq_npm_finding_triplet') THEN
        ALTER TABLE ma_moulinette.npm_finding ADD CONSTRAINT uq_npm_finding_triplet UNIQUE (scan_id, dependency_id, vulnerability_id);
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'fk_npm_finding_scan') THEN
        ALTER TABLE ma_moulinette.npm_finding ADD CONSTRAINT fk_npm_finding_scan FOREIGN KEY (scan_id)
            REFERENCES ma_moulinette.npm_scan(id) ON DELETE CASCADE;
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'fk_npm_finding_dependency') THEN
        ALTER TABLE ma_moulinette.npm_finding ADD CONSTRAINT fk_npm_finding_dependency FOREIGN KEY (dependency_id)
            REFERENCES ma_moulinette.npm_dependency(id) ON DELETE RESTRICT;
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'fk_npm_finding_vulnerability') THEN
        ALTER TABLE ma_moulinette.npm_finding ADD CONSTRAINT fk_npm_finding_vulnerability FOREIGN KEY (vulnerability_id)
            REFERENCES ma_moulinette.npm_vulnerability(id) ON DELETE RESTRICT;
    END IF;

    RAISE NOTICE 'npm_finding : droits, commentaires, indexes et contraintes à jour.';
END $$;

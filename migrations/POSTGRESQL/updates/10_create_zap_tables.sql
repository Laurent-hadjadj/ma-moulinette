-- ===============================================
-- zap_processing_queue
-- ===============================================
DO $$
DECLARE
    table_exists BOOLEAN;
BEGIN
    SELECT EXISTS (
        SELECT FROM pg_catalog.pg_tables
        WHERE schemaname = 'ma_moulinette' AND tablename = 'zap_processing_queue'
    ) INTO table_exists;

    IF table_exists THEN
        RAISE NOTICE 'La table ma_moulinette.zap_processing_queue existe déjà.';
    ELSE
        CREATE TABLE ma_moulinette.zap_processing_queue
        (
            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            ulid              VARCHAR(26) NOT NULL UNIQUE,
            payload_gz        BYTEA NOT NULL,
            payload_sha256    CHAR(64) NOT NULL,
            payload_size      INTEGER NOT NULL,
            content_type      VARCHAR(16) NOT NULL,
            maven_key         VARCHAR(511) NOT NULL,
            project_version   VARCHAR(64)  NOT NULL,
            target_url        VARCHAR(2048) NULL,
            status            VARCHAR(16) NOT NULL DEFAULT 'queued',
            attempts          INTEGER NOT NULL DEFAULT 0,
            created_at        TIMESTAMP(0) WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP(0),
            started_at        TIMESTAMP(0) WITH TIME ZONE NULL,
            processed_at      TIMESTAMP(0) WITH TIME ZONE NULL,
            error_message     TEXT NULL
        );
        RAISE NOTICE 'La table ma_moulinette.zap_processing_queue a été créée.';
    END IF;

    ALTER TABLE ma_moulinette.zap_processing_queue OWNER TO db_user;
    GRANT ALL ON TABLE ma_moulinette.zap_processing_queue TO db_user;

    COMMENT ON TABLE ma_moulinette.zap_processing_queue IS 'Queue d''ingestion des rapports ZAP (DAST) postes par la CI.';
    COMMENT ON COLUMN ma_moulinette.zap_processing_queue.ulid IS 'Identifiant public renvoyé au client (ULID Crockford base32).';
    COMMENT ON COLUMN ma_moulinette.zap_processing_queue.payload_gz IS 'JSON ZAP compresse (gzip niveau 6) - TOAST gere par PG.';
    COMMENT ON COLUMN ma_moulinette.zap_processing_queue.payload_sha256 IS 'sha256 du JSON décompressé - cle d''idempotence.';
    COMMENT ON COLUMN ma_moulinette.zap_processing_queue.maven_key IS 'Identification projet fournie par la CI (en-tête X-Maven-Key) - absente du payload ZAP lui-même.';
    COMMENT ON COLUMN ma_moulinette.zap_processing_queue.status IS 'queued | processing | done | failed';

    CREATE INDEX IF NOT EXISTS idx_zap_queue_status_created ON ma_moulinette.zap_processing_queue(status, created_at) WHERE status IN ('queued', 'processing');
    CREATE INDEX IF NOT EXISTS idx_zap_queue_project ON ma_moulinette.zap_processing_queue(maven_key, project_version);
    CREATE INDEX IF NOT EXISTS idx_zap_queue_created ON ma_moulinette.zap_processing_queue(created_at);

    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'uq_zap_payload_sha256') THEN
        ALTER TABLE ma_moulinette.zap_processing_queue ADD CONSTRAINT uq_zap_payload_sha256 UNIQUE (payload_sha256);
    END IF;

    RAISE NOTICE 'zap_processing_queue : droits, commentaires, indexes et contraintes à jour.';
END $$;


    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'fk_zap_scan_queue') THEN
        ALTER TABLE ma_moulinette.zap_scan ADD CONSTRAINT fk_zap_scan_queue FOREIGN KEY (queue_id)
            REFERENCES ma_moulinette.zap_processing_queue(id) ON DELETE SET NULL;
    END IF;

    RAISE NOTICE 'zap_scan : droits, commentaires, indexes et contraintes à jour.';

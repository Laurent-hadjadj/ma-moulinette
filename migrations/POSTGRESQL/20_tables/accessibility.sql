-- MODIF 26/10/2026 : nouvelle table pour stocker l'indicateur « Accessibilité »,
-- calculé par BatchCollecteAccessibilityController à partir du tag SonarQube
-- `accessibility` (css/web/javascript/typescript — pas de facette officielle
-- dédiée, pas de plugin tiers à activer, contrairement à Creedengo/
-- CREEDENGO_ENABLED). Snapshot courant (une ligne par maven_key, remplacée à
-- chaque collecte).
-- Note A-E (accessibility_rating, seuils SQALE 5/10/20/50% identiques au RCI
-- et à l'Empreinte Écologique) et détail par langage (css/web/javascript/
-- typescript).

-- ⚠️ Le script doit être lancé avec l'utilisateur propriétaire du schema
\c ma_moulinette;

DROP TABLE IF EXISTS ma_moulinette.accessibility;

CREATE TABLE ma_moulinette.accessibility
(
  id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  maven_key VARCHAR(255) NOT NULL,

  -- Accessibilité globale (tous langages confondus). Null si la collecte n'a
  -- jamais été lancée.
  accessibility_anomalies INT,
  accessibility_dette_minute INT,
  accessibility_rating VARCHAR(4),

  -- Détail par langage (css/web/javascript/typescript). Null si le langage
  -- n'est pas présent dans le projet (ncloc nul pour ce langage) ou dans les
  -- mêmes conditions que ci-dessus.
  accessibility_css_anomalies INT,
  accessibility_css_dette_minute INT,
  accessibility_css_rating VARCHAR(4),

  accessibility_web_anomalies INT,
  accessibility_web_dette_minute INT,
  accessibility_web_rating VARCHAR(4),

  accessibility_javascript_anomalies INT,
  accessibility_javascript_dette_minute INT,
  accessibility_javascript_rating VARCHAR(4),

  accessibility_typescript_anomalies INT,
  accessibility_typescript_dette_minute INT,
  accessibility_typescript_rating VARCHAR(4),

  -- Méta collecte
  mode_collecte VARCHAR(32),
  utilisateur_collecte VARCHAR(320),
  date_enregistrement TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

--- 2026-11-20 : un scan = un rapport npm audit --json pour (projet, version,
--- date). Compteurs pre-calcules, repris directement de metadata du rapport.
--- npm utilise "moderate", pas "medium" comme DependencyCheck.
--- dep_count_* (prod/dev/optional/peer/peerOptional) n'ont pas d'equivalent
--- DependencyCheck (pas de notion prod/dev pour un .jar Maven).

-- ⚠️ Le script doit être lancé avec l'utilisateur propriétaire du schema
\c ma_moulinette;

DROP TABLE IF EXISTS ma_moulinette.npm_scan CASCADE;

CREATE TABLE ma_moulinette.npm_scan
(
  id                      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  queue_id                BIGINT NULL,
  project_group           VARCHAR(255) NOT NULL,
  project_artifact        VARCHAR(255) NOT NULL,
  project_version         VARCHAR(64) NOT NULL,
  scan_date               TIMESTAMP(0) WITH TIME ZONE NOT NULL,
  audit_report_version    VARCHAR(8) NULL,
  vuln_count_critical     INTEGER NOT NULL DEFAULT 0,
  vuln_count_high         INTEGER NOT NULL DEFAULT 0,
  vuln_count_moderate     INTEGER NOT NULL DEFAULT 0,
  vuln_count_low          INTEGER NOT NULL DEFAULT 0,
  vuln_count_info         INTEGER NOT NULL DEFAULT 0,
  vuln_count_total        INTEGER NOT NULL DEFAULT 0,
  dep_count_prod          INTEGER NOT NULL DEFAULT 0,
  dep_count_dev           INTEGER NOT NULL DEFAULT 0,
  dep_count_optional      INTEGER NOT NULL DEFAULT 0,
  dep_count_peer          INTEGER NOT NULL DEFAULT 0,
  dep_count_peer_optional INTEGER NOT NULL DEFAULT 0,
  dep_count_total         INTEGER NOT NULL DEFAULT 0,
  created_at              TIMESTAMP(0) WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP(0)
);

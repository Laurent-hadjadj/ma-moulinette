--- 2026-10-28 : Nouvelle table — détail individuel de chaque vulnérabilité
---              OWASP classée (rule_key/categories/severity/source/module/
---              file_path/line/message), construite à partir du même appel
---              paginé que la table owasp agrégée (OwaspRuleClassifierService::
---              classify(), clé "details"), sans appel SonarQube supplémentaire.

-- ⚠️ Le script doit être lancé avec l'utilisateur propriétaire du schema
\c ma_moulinette;

DROP TABLE IF EXISTS ma_moulinette.owasp_details;

CREATE TABLE ma_moulinette.owasp_details
(
  id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

  maven_key VARCHAR(255) NOT NULL,
  referential_owasp INT NOT NULL DEFAULT 2017,
  version VARCHAR(32) NOT NULL,
  date_version TIMESTAMPTZ NOT NULL,

  rule_key VARCHAR(128) NOT NULL,
  -- Catégories A1..A10 du référentiel concernées par cette règle, concaténées
  -- (ex. "A4, A5" — une règle peut appartenir à plusieurs catégories).
  categories VARCHAR(64) NOT NULL,
  severity VARCHAR(8) NOT NULL,
  -- Origine de la règle : core (SonarSource) ou findsecbugs.
  source VARCHAR(16) NOT NULL,
  -- Module du fichier concerné : frontend, backend, autre ou inconnu.
  module VARCHAR(16) NOT NULL,

  file_path VARCHAR(255) NOT NULL,
  line INT,
  message VARCHAR(255) NOT NULL,

  mode_collecte VARCHAR(32),
  utilisateur_collecte VARCHAR(320),

  date_enregistrement TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

DROP TABLE IF EXISTS ma_moulinette.npm_finding CASCADE;

CREATE TABLE ma_moulinette.npm_finding
(
  id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  scan_id              BIGINT NOT NULL,
  dependency_id        BIGINT NOT NULL,
  vulnerability_id     BIGINT NOT NULL,
  severity_at_scan     VARCHAR(16) NOT NULL,
  cvss_at_scan         NUMERIC(3, 1) NULL,
  range                VARCHAR(255) NULL,
  installed_version    VARCHAR(255) NULL,
  is_direct            BOOLEAN NOT NULL DEFAULT false,
  fix_available        BOOLEAN NOT NULL DEFAULT false,
  fix_to_version       VARCHAR(64) NULL,
  fix_is_semver_major  BOOLEAN NULL,
  is_prod              BOOLEAN NULL,
  created_at           TIMESTAMP(0) WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP(0)
);

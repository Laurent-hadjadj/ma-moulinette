-- MODIF 2026-09-25 : nouvelle table pour stocker le RCI (Risk Criticality
-- Index, plugin sonar-rci porté en PHP), calculé par BatchCollecteRciController :
-- la mesure globale (ncloc/weight/indicator/rating) et son détail par module
-- (frontend/backend/autre/inconnu). Snapshot courant (une ligne par
-- maven_key, remplacée à chaque collecte), sur le modèle de clean_code —
-- pas de setup/control comme repartition, un seul appel SonarQube suffisant
-- à obtenir le résultat complet.

-- ⚠️ Le script doit être lancé avec l'utilisateur propriétaire du schema
\c ma_moulinette;

DROP TABLE IF EXISTS ma_moulinette.rci;

CREATE TABLE ma_moulinette.rci
(
  id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  maven_key VARCHAR(255) NOT NULL,

-- RCI Global
  ncloc INT NOT NULL DEFAULT 0,
  weight INT NOT NULL DEFAULT 0,
  indicator DOUBLE PRECISION,
  rating VARCHAR(4),

  -- Module frontend
  frontend_ncloc INT NOT NULL DEFAULT 0,
  frontend_weight INT NOT NULL DEFAULT 0,
  frontend_indicator DOUBLE PRECISION,
  frontend_rating VARCHAR(4),

  -- Module backend
  backend_ncloc INT NOT NULL DEFAULT 0,
  backend_weight INT NOT NULL DEFAULT 0,
  backend_indicator DOUBLE PRECISION,
  backend_rating VARCHAR(4),

  -- Module autre
  autre_ncloc INT NOT NULL DEFAULT 0,
  autre_weight INT NOT NULL DEFAULT 0,
  autre_indicator DOUBLE PRECISION,
  autre_rating VARCHAR(4),

  -- Fichiers non classés (ni frontend, ni backend, ni autre)
  inconnu_ncloc INT NOT NULL DEFAULT 0,
  inconnu_weight INT NOT NULL DEFAULT 0,
  inconnu_indicator DOUBLE PRECISION,
  inconnu_rating VARCHAR(4),

  -- Méta collecte
  mode_collecte VARCHAR(32),
  utilisateur_collecte VARCHAR(320),
  date_enregistrement TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

--- 2026-10-13 : un scan = un rapport ZAP pour (maven_key, project_version,
--- target_url, generated_at). Compteurs pre-calcules par niveau de risque ZAP.

-- Lien vers la queue d'ingestion source (pour audit/retraitement)
-- Identification projet fournie par la CI a l'upload (pas par le payload ZAP)
-- URL cible scannée (site[0].@name du rapport, ou en-tête X-Target-Url)
-- Version de ZAP ayant produit le rapport (@version)
-- Date de génération du rapport (@generated)
-- Compteurs pre-calcules par niveau de risque ZAP (éviter COUNT() au rendering)

-- ⚠️ Le script doit être lancé avec l'utilisateur propriétaire du schema
\c ma_moulinette;

DROP TABLE IF EXISTS ma_moulinette.zap_scan CASCADE;

CREATE TABLE ma_moulinette.zap_scan
(
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  queue_id BIGINT NULL,
  maven_key VARCHAR(511) NOT NULL,
  project_version VARCHAR(64) NOT NULL,
  target_url VARCHAR(2048) NULL,
  zap_version VARCHAR(32) NULL,
  generated_at TIMESTAMP(0) WITH TIME ZONE NOT NULL,
  alert_count_total INTEGER NOT NULL DEFAULT 0,
  risk_count_high INTEGER NOT NULL DEFAULT 0,
  risk_count_medium INTEGER NOT NULL DEFAULT 0,
  risk_count_low INTEGER NOT NULL DEFAULT 0,
  risk_count_informational INTEGER NOT NULL DEFAULT 0,
  created_at TIMESTAMP(0) WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP(0)
);

-- MODIF 2026-10-08 : nouvelle table pour stocker l'indicateur « Empreinte
-- Écologique », calculé par BatchCollecteEmpreinteEcologiqueController à
-- partir des plugins SonarQube Creedengo (creedengo-java/javascript/php/
-- python, repository prefix), activables via la propriété applicative
-- CREEDENGO_ENABLED (comme track-logger-method). Snapshot courant (une
-- ligne par maven_key, remplacée à chaque collecte).
-- Ajout de la note A-E (eco_rating, seuils SQALE 5/10/
-- 20/50% identiques au RCI) et du détail par langage (java/javascript/php/
-- python), sur le modèle du détail par module RCI.

-- ⚠️ Le script doit être lancé avec l'utilisateur propriétaire du schema
\c ma_moulinette;

DROP TABLE IF EXISTS ma_moulinette.eco_conception;

CREATE TABLE ma_moulinette.eco_conception
(
  id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  maven_key VARCHAR(255) NOT NULL,

  -- Empreinte Écologique globale (tous langages Creedengo confondus).
  -- Null si le plugin CREEDENGO_ENABLED est désactivé ou si la collecte n'a
  -- jamais été lancée.
  eco_anomalies INT,
  eco_dette_minute INT,
  eco_rating VARCHAR(4),

  -- Détail par langage (creedengo-java/javascript/php/python). Null si le
  -- langage n'est pas présent dans le projet (ncloc nul pour ce langage) ou
  -- dans les mêmes conditions que ci-dessus.
  eco_java_anomalies INT,
  eco_java_dette_minute INT,
  eco_java_rating VARCHAR(4),

  eco_javascript_anomalies INT,
  eco_javascript_dette_minute INT,
  eco_javascript_rating VARCHAR(4),

  eco_php_anomalies INT,
  eco_php_dette_minute INT,
  eco_php_rating VARCHAR(4),

  eco_python_anomalies INT,
  eco_python_dette_minute INT,
  eco_python_rating VARCHAR(4),

  -- Méta collecte
  mode_collecte VARCHAR(32),
  utilisateur_collecte VARCHAR(320),
  date_enregistrement TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

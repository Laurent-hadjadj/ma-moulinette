--- 2026-10-13 : référentiel global des règles ZAP (alertes).
--- Une row = une règle unique (deduplication par pluginid).

-- Identifiant de règle ZAP (pluginid), clé naturelle
-- CWE/WASC associés a la règle (constants, pas par instance)
-- Solution et références documentaires (texte fourni par ZAP)
-- Traçabilité : premiere et dernière apparition dans nos scans

-- ⚠️ Le script doit être lancé avec l'utilisateur propriétaire du schema
\c ma_moulinette;

DROP TABLE IF EXISTS ma_moulinette.zap_rule CASCADE;

CREATE TABLE ma_moulinette.zap_rule
(
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  pluginid VARCHAR(16) NOT NULL,
  name VARCHAR(255) NOT NULL,
  cweid INTEGER NULL,
  wascid INTEGER NULL,
  solution TEXT NOT NULL DEFAULT '',
  reference TEXT NOT NULL DEFAULT '',
  first_seen_at TIMESTAMP(0) WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP(0),
  last_seen_at TIMESTAMP(0) WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP(0)
);
